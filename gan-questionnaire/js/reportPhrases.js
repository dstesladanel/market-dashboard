// החלת סימון לשון. gender: "f" נקבה, אחרת זכר (גם "לא צוין").
export function applyGender(text, gender) {
  const female = gender === "f";
  return String(text || "").replace(/\{([^{}|]*)(?:\|([^{}]*))?\}/g, (_, a, b) => {
    if (b === undefined) return female ? a : "";
    return female ? b : a;
  });
}
